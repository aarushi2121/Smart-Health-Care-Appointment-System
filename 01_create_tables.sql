
-- SmartCare Appointment Management System
-- File: 01_create_tables.sql
-- Safe for existing tables: does not drop or recreate them.

SET SERVEROUTPUT ON;

DECLARE
    v_count NUMBER;
BEGIN
    -- Check PATIENTS
    SELECT COUNT(*)
    INTO v_count
    FROM user_tables
    WHERE table_name = 'PATIENTS';

    IF v_count = 0 THEN
        EXECUTE IMMEDIATE '
            CREATE TABLE patients (
                patient_id NUMBER GENERATED BY DEFAULT AS IDENTITY
                    PRIMARY KEY,
                patient_name VARCHAR2(100) NOT NULL,
                phone VARCHAR2(15),
                email VARCHAR2(100)
            )';
        DBMS_OUTPUT.PUT_LINE('PATIENTS table created.');
    ELSE
        DBMS_OUTPUT.PUT_LINE(
            'PATIENTS table already exists. Preserved.'
        );
    END IF;

    -- Check DOCTORS
    SELECT COUNT(*)
    INTO v_count
    FROM user_tables
    WHERE table_name = 'DOCTORS';

    IF v_count = 0 THEN
        EXECUTE IMMEDIATE '
            CREATE TABLE doctors (
                doctor_id NUMBER GENERATED BY DEFAULT AS IDENTITY
                    PRIMARY KEY,
                doctor_name VARCHAR2(100) NOT NULL,
                specialization VARCHAR2(100) NOT NULL
            )';
        DBMS_OUTPUT.PUT_LINE('DOCTORS table created.');
    ELSE
        DBMS_OUTPUT.PUT_LINE(
            'DOCTORS table already exists. Preserved.'
        );
    END IF;

    -- Check APPOINTMENTS
    SELECT COUNT(*)
    INTO v_count
    FROM user_tables
    WHERE table_name = 'APPOINTMENTS';

    IF v_count = 0 THEN
        DBMS_OUTPUT.PUT_LINE(
            'APPOINTMENTS table does not exist.'
        );
        DBMS_OUTPUT.PUT_LINE(
            'Create it using the correct columns and '
            || 'foreign keys for your existing application.'
        );
    ELSE
        DBMS_OUTPUT.PUT_LINE(
            'APPOINTMENTS table already exists. Preserved.'
        );
    END IF;
END;
/

-- Verify existing tables
SELECT table_name
FROM user_tables
WHERE table_name IN (
    'PATIENTS',
    'DOCTORS',
    'APPOINTMENTS'
)
ORDER BY table_name;
